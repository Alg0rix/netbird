#!/usr/bin/env bash
# List the upstream files the fork edits, ranked by changed lines, and write docs/fork/patch-surface.md.
# These are the only places an upstream merge can conflict. New fork-only files are listed as a count.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
base=${1:-$(git merge-base HEAD upstream/main)}
out=docs/fork/patch-surface.md
mkdir -p docs/fork
{
  echo "# Patch surface"
  echo
  echo "Generated by scripts/fork/surface.sh against upstream base $(git rev-parse --short "$base"). Do not edit by hand."
  echo
  echo "Fork-only files: $(git diff --diff-filter=A --name-only "$base" HEAD -- . ':!docs' ':!*_test.go' ':!e2e' | wc -l)."
  echo
  echo "| Added | Removed | Upstream file |"
  echo "| ---: | ---: | --- |"
  git diff --numstat --diff-filter=M "$base" HEAD -- . ':!docs' ':!*_test.go' ':!e2e' ':!*.pb.go' ':!*.gen.go' \
    | sort -rn | awk -F'\t' '{printf "| %s | %s | `%s` |\n",$1,$2,$3}'
  echo
  echo "Generated files (rebuild with scripts/fork/regen.sh, never merge by hand): *.pb.go, *.gen.go."
} > "$out"
echo "wrote $out"
